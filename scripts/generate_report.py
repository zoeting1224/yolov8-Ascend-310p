#!/usr/bin/env python3
"""性能报告工具：根据 YOLOv8 推理结果和 msprof 数据生成独立 HTML 报告。

本文件用于离线分析和报告展示，不参与摄像头实时推理流水线。
"""

import argparse
import base64
import csv
import html
import json
import mimetypes
from pathlib import Path


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--metrics", required=True, help="Inference metrics JSON")
    parser.add_argument("--profile-dir", required=True, help="PROF_* directory generated by msprof")
    parser.add_argument("--report", required=True, help="Output HTML report")
    return parser.parse_args()


def read_csv(path):
    if path is None or not path.exists():
        return []
    with path.open("r", encoding="utf-8-sig", newline="") as file:
        return list(csv.DictReader(file))


def find_report(profile_dir, pattern):
    output_dir = profile_dir / "mindstudio_profiler_output"
    matches = sorted(output_dir.glob(pattern))
    return matches[-1] if matches else None


def number(value, default=0.0):
    try:
        return float(str(value).strip())
    except (TypeError, ValueError):
        return default


def image_data_uri(path):
    image_path = Path(path)
    if not image_path.exists():
        return ""
    mime = mimetypes.guess_type(image_path.name)[0] or "image/jpeg"
    encoded = base64.b64encode(image_path.read_bytes()).decode("ascii")
    return f"data:{mime};base64,{encoded}"


def escape(value):
    return html.escape(str(value), quote=True)


def format_ms(value):
    return f"{number(value):.2f} ms"


def build_bars(rows, label_key, value_key, limit=20):
    selected = rows[:limit]
    maximum = max((number(row.get(value_key)) for row in selected), default=1.0) or 1.0
    bars = []
    for row in selected:
        value = number(row.get(value_key))
        width = max(value / maximum * 100, 0.8)
        label = escape(row.get(label_key, ""))
        op_type = escape(row.get("OP Type", ""))
        bars.append(f'<div class="bar-row"><div class="bar-label" title="{label}">{label}<span>{op_type}</span></div><div class="bar-track"><div class="bar-fill" style="width:{width:.2f}%"></div></div><div class="bar-value">{value:.3f} us</div></div>')
    return "".join(bars) or '<p class="empty">没有可用的逐算子数据。</p>'


def table_rows(rows, columns):
    rendered = []
    for row in rows:
        cells = "".join(f"<td>{escape(row.get(column, ''))}</td>" for column in columns)
        rendered.append(f"<tr>{cells}</tr>")
    return "".join(rendered)


