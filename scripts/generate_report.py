    report_path = Path(args.report).resolve()
    metrics = json.loads(metrics_path.read_text(encoding="utf-8"))

    op_summary_path = find_report(profile_dir, "op_summary_*.csv")
    op_statistic_path = find_report(profile_dir, "op_statistic_*.csv")
    api_statistic_path = find_report(profile_dir, "api_statistic_*.csv")
    fusion_path = find_report(profile_dir, "fusion_op_*.csv")
    op_rows = read_csv(op_summary_path)
    op_rows.sort(key=lambda row: number(row.get("Task Duration(us)")), reverse=True)
    statistic_rows = read_csv(op_statistic_path)
    statistic_rows.sort(key=lambda row: number(row.get("Total Time(us)")), reverse=True)
    api_rows = read_csv(api_statistic_path)
    fusion_rows = read_csv(fusion_path)

    model_execute_us = next((number(row.get("Time(us)")) for row in api_rows if row.get("API Name") == "ModelExecute"), 0.0)
    acl_execute_us = next((number(row.get("Time(us)")) for row in api_rows if row.get("API Name") == "aclmdlExecute"), 0.0)
    operator_total_us = sum(number(row.get("Task Duration(us)")) for row in op_rows)
    input_uri = image_data_uri(metrics["image"])
    output_uri = image_data_uri(metrics["output"])

    detection_columns = ["class_name", "confidence", "box_xyxy"]
    detection_rows = []
    for detection in metrics.get("detections", []):
        detection_rows.append({"class_name": detection["class_name"], "confidence": f'{number(detection["confidence"]):.4f}', "box_xyxy": ", ".join(f"{number(value):.1f}" for value in detection["box_xyxy"])})

    op_columns = ["Op Name", "OP Type", "Task Type", "Task Duration(us)", "Task Wait Time(us)", "aicore_time(us)", "memory_bound", "cube_utilization(%)"]
    statistic_columns = ["OP Type", "Core Type", "Count", "Total Time(us)", "Min Time(us)", "Avg Time(us)", "Max Time(us)", "Ratio(%)"]
    fusion_columns = ["Fusion Op", "Original Ops", "Memory Total(KB)"]
